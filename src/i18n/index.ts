let initialized = false

export function initI18n(): typeof i18next {
  if (!initialized) {
    void i18next.use(initReactI18next).init({
      lng: 'zh',
      fallbackLng: 'zh',
      defaultNS: defaultNamespace,
      resources: {
        zh: zhDict,
      },
      interpolation: {
        escapeValue: false,
      },
    })
    initialized = true
  }
  return i18next
}
