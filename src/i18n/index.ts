let initialized = false

export function initI18n(
  storage?: Storage | null,
  navigatorLanguage?: string,
): typeof i18next {
  if (!initialized) {
    // 存储不可用（部分测试环境）且未显式传入浏览器语言时，保持中文默认；
    // 「跟随浏览器」的探测只在真实浏览器里发生（有 localStorage 可持久化偏好）
    const saved = loadSavedLanguage(storage)
    const lng =
      saved ??
      (navigatorLanguage === undefined ? 'zh' : resolveInitialLanguage(null, navigatorLanguage))
    void i18next.use(initReactI18next).init({
      lng,
      // 英文缺键回退中文：未翻译条目不得显示裸 key
      fallbackLng: 'zh',
      defaultNS: defaultNamespace,
      resources: {
        zh: zhDict,
        en: enDict,
      },
      interpolation: {
        escapeValue: false,
      },
    })
    initialized = true
  }
  return i18next
}

/** 切换界面语言：立即生效并持久化偏好（真实浏览器默认写 localStorage；测试可注入） */
export function setAppLanguage(
  language: AppLanguage,
  storage: Storage | null = typeof window === 'undefined' ? null : window.localStorage,
): Promise<void> {
  persistLanguage(language, storage)
  return i18next.changeLanguage(language).then(() => undefined)
}
